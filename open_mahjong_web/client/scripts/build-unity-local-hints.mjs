// Keep Unity WebGL and the 2D client on the same pure hint calculators.
import {build} from 'esbuild'
import {fileURLToPath} from 'node:url'
import {writeFileSync} from 'node:fs'

export const pluginPath=fileURLToPath(new URL('../../../open_mahjong_unity/Assets/Plugins/LocalHintsWorker.jslib',import.meta.url))
export async function localHintPlugin(){
  const result=await build({entryPoints:[fileURLToPath(new URL('../src/game2d/calc/localHintWorker.ts',import.meta.url))],bundle:true,write:false,format:'iife',platform:'browser',target:'es2020',minify:true})
  return '// Generated by open_mahjong_web/client/scripts/build-unity-local-hints.mjs.\n'+
    'mergeInto(LibraryManager.library, {$OMLocalHintWorkerSource: function () { return '+JSON.stringify(result.outputFiles[0].text)+'; }});\n'
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
  writeFileSync(pluginPath,await localHintPlugin());console.log(pluginPath)
}
