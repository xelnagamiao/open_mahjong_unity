export function staticPageForPath(path) {
  const normalized = String(path).replace(/\/+$/, '')
  return STATIC_PAGES.find(page => page.path === normalized) || null
}

export function languageVersions(page) {
  return STATIC_PAGES.filter(other => other.family === page.family)
}

export function pageAlternates(page, domain) {
  const versions = languageVersions(page)
  if (versions.length < 2) return []
  return [
    ...versions.map(other => ({ language: other.locale, href: domain + other.path })),
    { language: 'x-default', href: domain + (versions.find(other => other.locale === 'en') || versions[0]).path },
  ]
}

export function pageStructuredData(page, domain) {
  const url = domain + page.path
  return {
    '@context': 'https://schema.org', '@type': 'WebPage', '@id': url + '#page', url,
    name: page.title, description: page.description, inLanguage: page.locale,
    isPartOf: { '@type': 'WebSite', '@id': domain + '/#website', name: 'Salasasa', url: domain + '/' },
  }
}
