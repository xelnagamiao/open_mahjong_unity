export const game2dMessages = Object.fromEntries(['en', 'ja', 'fr'].map((language, index) => [
  language, Object.fromEntries(entries.map(([source, ...translations]) => [source, translations[index]])),
]))

// Legacy replay/canvas labels are generated by the record engine before reaching Vue.
export function game2dTextPatterns(language) {
  const format = (key, values) => game2dMessages[language][key].replace(/\{(\w+)\}/g, (_, name) => values[name])
  const kongLabels = {
    en: { 明杠: 'Melded kong', 暗杠: 'Concealed kong', 加杠: 'Added kong', 和牌: 'Win', 财神: 'Joker' },
    ja: { 明杠: '明槓', 暗杠: '暗槓', 加杠: '加槓', 和牌: '和了', 财神: '財神' },
    fr: { 明杠: 'Kong exposé', 暗杠: 'Kong caché', 加杠: 'Kong complété', 和牌: 'Victoire', 财神: 'Joker' },
  }
  return [
    { match: /^([1-9])万$/, replace: rank => format('{rank}万', { rank }) },
    { match: /^([1-9])[筒饼]$/, replace: rank => format('{rank}筒', { rank }) },
    { match: /^([1-9])条$/, replace: rank => format('{rank}条', { rank }) },
    { match: /^余 (\d+) 枚$/, replace: count => format('剩余 {count} 张', { count }) },
    { match: /^(\d+)\s*番$/, replace: count => format('{count} 番', { count }) },
    { match: /^(\d+)\s*秒$/, replace: count => format('{count} 秒', { count }) },
    { match: /^(\d+)庄$/, replace: count => format('{count}庄', { count }) },
    { match: /^(.+) 自摸和$/, replace: winner => format('{winner} 自摸和', { winner }) },
    { match: /^(.+) 和,\s+(.+) 铳$/, replace: (winner, discarder) => format('{winner} 和, {discarder} 铳', { winner, discarder }) },
    { match: /^共 ([\d.]+) 番 \(各 ([\d.-]+')\)$/, replace: (fan, loss) => format('共 {fan} 番 (各 {loss})', { fan, loss }) },
    { match: /^共 ([\d.]+) 番 \(([\d.-]+')\)$/, replace: (fan, loss) => format('共 {fan} 番 ({loss})', { fan, loss }) },
    { match: /^(明杠|暗杠|加杠|和牌|财神)：东([+-]?\d+) 南([+-]?\d+) 西([+-]?\d+) 北([+-]?\d+)$/, replace: (kind, ...scores) => `${kongLabels[language][kind]}: ${['东', '南', '西', '北'].map((wind, index) => `${game2dMessages[language][wind]} ${scores[index]}`).join(' / ')}` },
    { match: /^连庄上限掷骰：(.+)；下庄为本局([东南西北])家。$/, replace: (dice, wind) => format('连庄上限掷骰：{dice}；下庄为本局{wind}家。', { dice: dice.replaceAll('、', ', '), wind: game2dMessages[language][wind] }) },
  ]
}
