import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const client = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const resources = path.resolve(client, '../../open_mahjong_unity/Assets/Resources/Localization')
const read = name => JSON.parse(fs.readFileSync(path.join(resources, name), 'utf8'))
const source = read('PlatformUI.json')
const entries = list => Object.fromEntries(list.map(entry => [entry.key, entry.text]))
const base = {
  en: Object.fromEntries(source.entries.map(entry => [entry.key, entry.en])),
  ja: entries(read('PlatformUI.ja.json').entries),
}
const outputs = new Map([
  ['src/i18n/platform-base-messages.js', '// Generated by scripts/sync-platform-localization.mjs from the Unity catalogs.\n// Web-specific wording takes precedence over these shared fallback messages.\nexport default ' + JSON.stringify(base, null, 2) + '\n'],
])
for (const language of ['fr', 'de', 'ru', 'es']) {
  const catalog = read(`PlatformUI.${language}.json`)
  const value = {
    messages: entries(catalog.entries),
    contexts: Object.fromEntries(catalog.contexts.map(context => [context.name, entries(context.entries)])),
    units: Object.fromEntries(catalog.units.map(({ key, ...forms }) => [key, forms])),
  }
  outputs.set(`src/i18n/locales/${language}.js`, '// Generated by scripts/sync-platform-localization.mjs. Source keys and protocol values remain unchanged.\nexport default ' + JSON.stringify(value, null, 2) + '\n')
}
const stale = []
for (const [relative, value] of outputs) {
  const file = path.join(client, relative)
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === value) continue
  if (process.argv.includes('--check')) stale.push(relative)
  else fs.writeFileSync(file, value)
}
if (stale.length) {
  console.error('Localization catalogs are out of sync. Run node scripts/sync-platform-localization.mjs.\n' + stale.join('\n'))
  process.exitCode = 1
} else console.log(process.argv.includes('--check') ? 'Shared localization catalogs are synchronized.' : 'Synchronized shared localization catalogs.')
