const TITLE_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS titles (
    title_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 3) PRIMARY KEY CHECK (title_id > 1),
    name VARCHAR(24) NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
    description VARCHAR(200) NOT NULL DEFAULT '',
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS user_titles (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    title_id INTEGER NOT NULL REFERENCES titles(title_id),
    granted_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    grant_reason VARCHAR(500) NOT NULL DEFAULT '',
    PRIMARY KEY (user_id, title_id)
);
CREATE INDEX IF NOT EXISTS idx_user_titles_title ON user_titles(title_id);
INSERT INTO titles (title_id, name, description) VALUES (2, '最初的初段', '该头衔授予在国标麻将匹配中，第一个成为初段的玩家') ON CONFLICT DO NOTHING;
UPDATE titles SET name = '最初的初段', updated_at = CURRENT_TIMESTAMP
WHERE title_id = 2 AND name = '初段'
  AND NOT EXISTS (SELECT 1 FROM titles WHERE name = '最初的初段');
INSERT INTO titles (name, description)
SELECT seed.name, seed.description FROM (VALUES
    ('冠绝一世', '该头衔授予在国标麻将匹配中，第一个达成七段的玩家'),
    ('千恋万花', '该头衔授予在国标麻将匹配中，在和牌时拥有八张花牌的玩家'),
    ('鲨国左护法', '赞助金额达到 100 元且低于 500 元的玩家'),
    ('鲨国右护法', '赞助金额达到 500 元的玩家')
) AS seed(name, description)
WHERE NOT EXISTS (SELECT 1 FROM titles WHERE name = seed.name)
ON CONFLICT (name) DO NOTHING;
INSERT INTO user_titles (user_id, title_id, grant_reason)
SELECT us.user_id, us.title_id, '迁移原有佩戴头衔'
FROM user_settings us JOIN titles t ON t.title_id = us.title_id
ON CONFLICT (user_id, title_id) DO NOTHING;
`;

async function ensureTitleTables(db = require('../config/database')) {
  // One transaction also makes schema initialization safe against partial startup.
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    await client.query(TITLE_SCHEMA_SQL);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally { client.release(); }
}

async function grantSponsorTitles(client, adminUserId, userId, amount, reason) {
  const result = await client.query(`
    INSERT INTO user_titles (user_id, title_id, granted_by, grant_reason)
    SELECT $1, t.title_id, $2, $3
    FROM titles t
    WHERE (t.name = '鲨国左护法' AND $4::numeric >= 100 AND $4::numeric < 500)
       OR (t.name = '鲨国右护法' AND $4::numeric >= 500)
    ON CONFLICT (user_id, title_id) DO NOTHING
    RETURNING *
  `, [userId, adminUserId, reason, amount]);
  return result.rows;
}

async function grantSponsorTitlesForAllUsers(db = require('../config/database')) {
  await db.query(`
    INSERT INTO user_titles (user_id, title_id, grant_reason)
    SELECT u.user_id, t.title_id, '根据历史赞助金额自动授予头衔'
    FROM users u
    JOIN titles t ON (t.name = '鲨国左护法' AND u.sponsor_amount >= 100 AND u.sponsor_amount < 500)
                 OR (t.name = '鲨国右护法' AND u.sponsor_amount >= 500)
    ON CONFLICT (user_id, title_id) DO NOTHING
  `);
}

module.exports = { TITLE_SCHEMA_SQL, ensureTitleTables, grantSponsorTitles, grantSponsorTitlesForAllUsers };
