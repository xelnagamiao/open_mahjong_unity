function frenchTileText(value) {
  return String(value).replace(/[1-9][万饼筒条]|红中|[东南西北中白发]|未翻财/g, (tile) => {
    if (fr[tile]) return fr[tile]
    return `${tile[0]} ${fr[tile[1]] || tile[1]}`
  })
}

function frenchPageText(value) {
  const source = String(value)
  if (Object.prototype.hasOwnProperty.call(fr, source)) return fr[source]
  for (const pattern of frTextPatterns) {
    const match = source.match(pattern.match)
    if (match) return pattern.replace(...match.slice(1))
  }
  return source
}

