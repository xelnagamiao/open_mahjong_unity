using System.Collections.Generic;
using System.Linq;
using TMPro;
using UnityEditor;
using UnityEngine;

public static class PrefabBaselineBaker
{
    // Some UI bakers reconstruct a prefab from a different source. Its own typography is authored locally.
    public static GameObject Save(GameObject rebuilt, string path)
    {
        var previous = AssetDatabase.LoadAssetAtPath<GameObject>(path);
        if (previous)
        {
            var objects = new Dictionary<Transform, Transform>();
            Match(previous.transform, rebuilt.transform, objects);
            var rows = new Dictionary<PlatformBaselineRow, PlatformBaselineRow>();
            foreach (var pair in objects.ToArray())
            {
                var targetRows = pair.Value.GetComponents<PlatformBaselineRow>();
                int index = 0;
                foreach (var old in pair.Key.GetComponents<PlatformBaselineRow>())
                {
                    var row = index < targetRows.Length ? targetRows[index] : pair.Value.gameObject.AddComponent<PlatformBaselineRow>();
                    row.rowName = old.rowName;
                    row.anchor = old.anchor && old.anchor.IsChildOf(previous.transform)
                        ? (RectTransform)RestoreAnchor(old.anchor, objects) : old.anchor;
                    row.referenceSize = old.referenceSize;
                    row.verticalOffset = old.verticalOffset;
                    row.enabled = old.enabled;
                    rows.Add(old, row);
                    index++;
                }
            }
            foreach (var old in previous.GetComponentsInChildren<PlatformTextBaseline>(true))
            {
                if (!objects.TryGetValue(old.transform, out var target) || !target.GetComponent<TextMeshProUGUI>()) continue;
                var label = target.GetComponent<PlatformTextBaseline>() ?? target.gameObject.AddComponent<PlatformTextBaseline>();
                PlatformBaselineRow row = null;
                if (old.row) rows.TryGetValue(old.row, out row);
                label.designSize = old.designSize;
                label.Configure(old.mode, row);
                label.enabled = old.enabled;
            }
        }
        return PrefabUtility.SaveAsPrefabAsset(rebuilt, path);
    }

    static Transform RestoreAnchor(Transform source, Dictionary<Transform, Transform> objects)
    {
        if (objects.TryGetValue(source, out var existing)) return existing;
        // A manually added guide may have no equivalent in a layout regenerated by a baker.
        var parent = RestoreAnchor(source.parent, objects);
        var guideObject = source is RectTransform ? new GameObject(source.name, typeof(RectTransform)) : new GameObject(source.name);
        Transform guide = guideObject.transform;
        guide.SetParent(parent, false);
        if (source is RectTransform rect && guide is RectTransform copy)
        {
            copy.anchorMin = rect.anchorMin;
            copy.anchorMax = rect.anchorMax;
            copy.pivot = rect.pivot;
            copy.sizeDelta = rect.sizeDelta;
            copy.anchoredPosition3D = rect.anchoredPosition3D;
        }
        else guide.localPosition = source.localPosition;
        guide.localRotation = source.localRotation;
        guide.localScale = source.localScale;
        objects.Add(source, guide);
        return guide;
    }

    static void Match(Transform previous, Transform rebuilt, Dictionary<Transform, Transform> objects)
    {
        objects.Add(previous, rebuilt);
        // Match repeated sibling names in order as well as unique names.
        var children = rebuilt.Cast<Transform>().GroupBy(child => child.name)
            .ToDictionary(group => group.Key, group => new Queue<Transform>(group));
        foreach (Transform child in previous)
            if (children.TryGetValue(child.name, out var targets) && targets.Count > 0)
                Match(child, targets.Dequeue(), objects);
    }
}
