"""从统计配表生成 Web/Unity 同名入口。修改配表后运行本脚本并重新生成 Excel。"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "open_mahjong_server/server/database/statistics_rules.json"
sys.path.insert(0, str(ROOT / "open_mahjong_server"))


def sync():
    catalog = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = catalog["rules"]
    assert len({r["sub_rule"] for r in rows}) == len(rows)
    assert len({r["key"] for r in rows}) == len(rows)
    assert len({r["stats_name"] for r in rows if r["basic_stats"]}) == sum(r["basic_stats"] for r in rows)
    assert all(isinstance(r["home_header"], bool) for r in rows)
    assert all(r["basic_stats"] and r["home_label"].strip() for r in rows if r["home_header"])
    from server.match.rating_rules import QUEUES
    from server.database.statistics_catalog import resolve_statistics_identity
    for row in rows:
        ranked = set()
        for queue in QUEUES.values():
            sub = resolve_statistics_identity(queue.rule, queue.sub_rule, {},
                f"{queue.rounds}/{queue.player_count}")[1]
            if sub == row["sub_rule"]:
                ranked.add(f"{queue.rounds}/4" + ("_sanma" if queue.player_count == 3 else "") + "_rank")
        row["ranked_modes"] = sorted(ranked)
        row["matchmaking"] = bool(ranked)
        assert len(row["custom_modes"]) == len(set(row["custom_modes"]))
        assert row["basic_stats"] or not (row["custom_modes"] or ranked or row["fan_stats"])
    SOURCE.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    target = ROOT / "open_mahjong_web/shared/statisticsRules.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    def literal(value):
        return json.dumps(value, ensure_ascii=False)
    entries = "\n".join('        new Entry(%s, %s, %s, %s, %d, %s, %s, new string[]{%s}, new string[]{%s}),' % (
        literal(r["key"]), literal(r["rule"]), literal(r["sub_rule"]), literal(r["stats_name"]),
        r["player_count"], str(r["fan_stats"]).lower(), str(r["standard"]).lower(),
        ', '.join(literal(v) for v in r["custom_modes"]), ', '.join(literal(v) for v in r["ranked_modes"])) for r in rows if r["basic_stats"])
    source = '''// Generated by open_mahjong_server/scripts/sync_statistics_catalog.py. Edit statistics_rules.json.
using System;
using System.Collections.Generic;

public static class PlayerInfoRuleCatalog {
    public const string GuobiaoSanma = "guobiao_sanma", GuangdongTuidao = "guangdong_tuidao",
        ShanghaiQinghunpeng = "shanghai_qinghunpeng", Nanque = "nanque";
    public static readonly string[] PrimaryRules = { "guobiao", "riichi", "qingque", "sichuan" };
    private sealed class Entry {
        public readonly string Key, Rule, SubRule, Name;
        public readonly int Players;
        public readonly bool Fans, Standard;
        public readonly string[] CustomModes, RankedModes;
        public Entry(string key, string rule, string subRule, string name, int players, bool fans, bool standard, string[] customModes, string[] rankedModes) {
            Key=key; Rule=rule; SubRule=subRule; Name=name; Players=players; Fans=fans; Standard=standard;
            CustomModes=customModes; RankedModes=rankedModes;
        }
    }
    private static readonly Entry[] Entries = {
ENTRIES
    };
    private static Entry Find(string key) => Array.Find(Entries, e => e.Key == (key == "jiandan" ? Nanque : key));
    public static List<KeyValuePair<string,string>> OtherRules(bool ranked) {
        var rows = new List<KeyValuePair<string,string>>();
        foreach (var row in Entries) {
            if (Array.IndexOf(PrimaryRules,row.Key)>=0 || (ranked && row.RankedModes.Length == 0)) continue;
            rows.Add(new KeyValuePair<string,string>(row.Key, Name(row.Key)));
        }
        return rows;
    }
    public static string SourceRule(string key) => Find(key)?.Rule;
    public static string SubRule(string key) => Find(key)?.SubRule;
    public static string Name(string key) => Find(key)?.Name;
    public static int PlayerCount(string key) => Find(key)?.Players ?? 4;
    public static bool IsRiichi(string key) => SourceRule(key)=="riichi";
    public static bool Supports(string key) => Find(key)!=null;
    public static bool HasFanStats(string key) => Find(key)?.Fans ?? false;
    public static bool IsStandard(string key) => Find(key)?.Standard ?? false;
    public static string[] Modes(string key, bool ranked) {
        var row = Find(key);
        return row == null ? Array.Empty<string>() : (string[])(ranked ? row.RankedModes : row.CustomModes).Clone();
    }
}
'''.replace("ENTRIES", entries)
    (ROOT / "open_mahjong_unity/Assets/Scripts/UI/PlayerInfo/PlayerInfoRuleCatalog.cs").write_text(source, encoding="utf-8")
    print(f"Synced {len(rows)} subrules ({sum(r['basic_stats'] for r in rows)} statistics entries)")


if __name__ == "__main__":
    sync()
