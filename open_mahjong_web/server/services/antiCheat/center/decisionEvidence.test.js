"use strict";
const test = require("node:test"), assert = require("node:assert/strict");
const { Pool, Client } = require("pg");
const { ensureDecisionFacts, VERSION } = require("./decisionEvidence");
const S = "anti_cheat_center";
test("decision cache batches only missing games, preserves event scope and invalidates on replaced facts", {skip: process.env.ANTI_CHEAT_INTEGRATION !== "1"}, async t => {
  require("dotenv").config({path: require("path").resolve(__dirname,"../../../../.env")});
  const host=process.env.DB_HOST||"localhost";
  assert.ok(["localhost","127.0.0.1","::1"].includes(host));
  const config={host,port:Number(process.env.DB_PORT)||5432,user:process.env.DB_USER||"postgres",password:process.env.DB_PASSWORD};
  const db="om_ac_decision_test_"+require("crypto").randomUUID().replaceAll("-","");
  const admin=new Client({...config,database:"postgres"}); await admin.connect();
  await admin.query(`CREATE DATABASE "${db}"`);
  const pool=new Pool({...config,database:db});
  t.after(async()=>{await pool.end();assert.match(db,/^om_ac_decision_test_[a-f0-9]+$/);await admin.query(`DROP DATABASE "${db}"`);await admin.end();});
  await pool.query(`CREATE SCHEMA ${S}; CREATE TABLE ${S}.games(game_id text PRIMARY KEY);
    CREATE TABLE ${S}.evidence(game_id text REFERENCES ${S}.games ON DELETE CASCADE,ordinal int,pair_id text,payload jsonb,PRIMARY KEY(game_id,ordinal));
    INSERT INTO ${S}.games VALUES('a'),('b'),('empty');`);
  const add=async(g,i,p,f,legal,helpful,tile=11)=>pool.query(`INSERT INTO ${S}.evidence VALUES($1,$2,$3,$4)`,[g,i,p,JSON.stringify({family:f,tile,legal_choices:legal,helpful_choices:helpful})]);
  await add('a',1,'ab','MELD',[11,12],[11]);
  await add('a',2,'ab','MELD',[11,11],[11]);
  await add('a',3,'ab','RON',[11,12],[11,12]);
  await add('a',4,'ab','RON',undefined,undefined);
  await add('a',5,'ab','MELD',[11,"12"],[11]);
  await add('a',6,'ba','RON',[11],[11]);
  await add('a',7,'ab','SPECIAL',[11],[11]);
  await add('b',1,'ab','MELD',[11,12],[11]);
  assert.deepEqual(await ensureDecisionFacts(pool,['a']),{games:1,pair_rows:2,version:VERSION});
  const get=async()=> (await pool.query(`SELECT payload FROM ${S}.decision_facts WHERE game_id='a' AND pair_id='ab'`)).rows[0].payload;
  const payload=await get();
  assert.deepEqual(payload.channels.ALL,{with_nonhelpful_alternative:1,sole_legal_candidate:1,all_candidates_help:1,unknown:2,sampled_events:5});
  assert.equal(payload.channels.MELD.sampled_events,3);
  assert.equal(payload.channels.RON.sampled_events,2);
  assert.match(payload.scope,/not_all_decisions/);
  assert.equal((await ensureDecisionFacts(pool,['a'])).games,0);
  assert.equal((await ensureDecisionFacts(pool,[])).games,0);
  assert.equal((await ensureDecisionFacts(pool)).games,2);
  assert.equal((await ensureDecisionFacts(pool)).games,0);
  assert.equal((await pool.query(`SELECT count(*)::int n FROM ${S}.decision_facts WHERE game_id='empty' AND pair_id=''`)).rows[0].n,1);
  await pool.query(`DELETE FROM ${S}.games WHERE game_id='a'; INSERT INTO ${S}.games VALUES('a');`);
  await add('a',1,'ab','RON',[11],[11]);
  assert.equal((await ensureDecisionFacts(pool)).games,1);
  assert.equal((await get()).channels.ALL.sampled_events,1);
  assert.equal((await get()).channels.MELD.sampled_events,0);
  await pool.query(`UPDATE ${S}.decision_facts SET payload='{"version":"old"}' WHERE game_id='empty' AND pair_id=''`);
  assert.equal((await ensureDecisionFacts(pool)).games,1);
});
